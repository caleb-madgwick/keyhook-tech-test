"""Merge ChatGPT batches (data/blind_raw/batch_*.json) into data/blind_test_set.json, validate
every message, and print the label mix plus the labels a human should hand-check.

    .venv/bin/python scripts/build_blind_set.py

The blind set was generated by ChatGPT from Keyhook's label definitions only (it never saw our
system prompt or the generated suite). Labels are NOT edited here; corrections are made by hand
in the raw batch files and recorded in data/blind_label_review.json.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from triage.schema import CATEGORIES, URGENCIES  # noqa: E402

RAW = ROOT / "data" / "blind_raw"
OUT = ROOT / "data" / "blind_test_set.json"
SEED = ROOT / "tenant_emails.json"


def problems(m: dict) -> list[str]:
    out = []
    for f in ("id", "received_at", "from_name", "subject", "body", "expected"):
        if f not in m:
            out.append(f"missing {f}")
    e = m.get("expected", {})
    if e.get("category") not in CATEGORIES:
        out.append(f"bad category {e.get('category')!r}")
    if e.get("urgency") not in URGENCIES:
        out.append(f"bad urgency {e.get('urgency')!r}")
    if not isinstance(e.get("escalate_to_human"), bool):
        out.append("escalate_to_human not a bool")
    also = e.get("also_mentions", [])
    if not isinstance(also, list) or any(c not in CATEGORIES for c in also):
        out.append(f"bad also_mentions {also!r}")
    elif e.get("category") in also:
        out.append("also_mentions repeats the primary category")
    if not e.get("expected_action"):
        out.append("empty expected_action")
    try:
        datetime.fromisoformat(str(m.get("received_at", "")).replace("Z", "+00:00"))
    except ValueError:
        out.append(f"bad received_at {m.get('received_at')!r}")
    return out


def main() -> None:
    messages: list[dict] = []
    for path in sorted(RAW.glob("batch_*.json")):
        batch = json.loads(path.read_text())
        print(f"{path.name}: {len(batch)} messages")
        messages += batch

    ids = Counter(m.get("id") for m in messages)
    errors = [f"{i}: duplicate id" for i, n in ids.items() if n > 1]
    errors += [f"{m.get('id')}: {p}" for m in messages for p in problems(m)]
    seed_bodies = {m["body"].strip() for m in json.loads(SEED.read_text())["messages"]}
    errors += [f"{m['id']}: copies a Keyhook seed message" for m in messages if m.get("body", "").strip() in seed_bodies]
    if errors:
        print("\nVALIDATION ERRORS:\n  " + "\n  ".join(errors))
        sys.exit(1)

    seed = json.loads(SEED.read_text())
    OUT.write_text(json.dumps({
        "description": "Blind test set: generated by ChatGPT from Keyhook's label_definitions and two seed "
                       "examples only (never saw this agent's prompt or the generated suite). Labels by "
                       "ChatGPT; emergency, escalation and low-confidence labels hand-checked (see "
                       "data/blind_label_review.json).",
        "label_definitions": seed["label_definitions"],
        "messages": messages,
    }, indent=2, ensure_ascii=False) + "\n")

    exp = [m["expected"] for m in messages]
    print(f"\nWrote {len(messages)} messages to {OUT.relative_to(ROOT)}")
    print("category:   ", dict(Counter(e["category"] for e in exp).most_common()))
    print("urgency:    ", dict(Counter(e["urgency"] for e in exp).most_common()))
    print("escalate:   ", dict(Counter(e["escalate_to_human"] for e in exp)))
    print("multi-issue:", sum(bool(e["also_mentions"]) for e in exp))
    print("low conf:   ", sum(m["test_meta"].get("label_confidence") == "low" for m in messages))

    print("\nHAND-CHECK (emergency / escalated / low-confidence):")
    for m in messages:
        e, tm = m["expected"], m.get("test_meta", {})
        if e["urgency"] == "emergency" or e["escalate_to_human"] or tm.get("label_confidence") == "low":
            flags = [f for f, on in (("EMERG", e["urgency"] == "emergency"), ("ESC", e["escalate_to_human"]),
                                     ("LOW", tm.get("label_confidence") == "low")) if on]
            also = f" +{','.join(e['also_mentions'])}" if e["also_mentions"] else ""
            print(f"  {m['id']} [{' '.join(flags)}] {e['category']}{also} / {e['urgency']} / esc={e['escalate_to_human']}"
                  f"  | {m['subject'][:45]}")
            if tm.get("alternative_label"):
                print(f"      alt: {tm['alternative_label'][:110]}")


if __name__ == "__main__":
    main()
